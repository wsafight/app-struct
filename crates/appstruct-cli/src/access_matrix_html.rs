use std::fmt::Write as _;

pub(crate) struct MatrixActor {
    pub label: String,
    pub decisions: Vec<MatrixDecision>,
}

#[derive(Clone, Copy)]
pub(crate) struct MatrixDecision {
    pub code: &'static str,
    pub label: &'static str,
    pub css_class: &'static str,
}

pub(crate) struct MatrixRowMeta {
    pub entity: String,
    pub operation: String,
    pub field: Option<String>,
}

pub(crate) fn render_html(
    app_name: &str,
    rows: &[MatrixRowMeta],
    actors: &[MatrixActor],
) -> String {
    let mut out = String::with_capacity(4096);
    let _ = writeln!(
        out,
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{} — Access Permission Matrix</title>
<style>
  :root {{ --bg: #0f172a; --card: #1e293b; --border: #334155; --text: #f1f5f9; --muted: #94a3b8; }}
  body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; background: var(--bg); color: var(--text); margin: 0; padding: 24px; }}
  h1 {{ margin: 0 0 6px; font-size: 22px; }}
  .sub {{ color: var(--muted); font-size: 13px; margin-bottom: 18px; }}
  .controls {{ display: flex; gap: 12px; margin-bottom: 16px; flex-wrap: wrap; }}
  input {{ background: var(--card); border: 1px solid var(--border); color: var(--text); padding: 8px 12px; border-radius: 6px; width: 280px; font-size: 14px; }}
  .wrap {{ overflow-x: auto; border: 1px solid var(--border); border-radius: 8px; background: var(--card); }}
  table {{ width: 100%; border-collapse: collapse; font-size: 13px; }}
  th, td {{ padding: 9px 12px; border-bottom: 1px solid var(--border); text-align: left; white-space: nowrap; }}
  th {{ background: #0b1220; position: sticky; top: 0; font-weight: 600; }}
  tr:hover td {{ background: rgba(148,163,184,0.08); }}
  .badge {{ display: inline-block; padding: 2px 8px; border-radius: 999px; font-size: 11px; font-weight: 600; }}
  .allowed {{ background: rgba(34,197,94,0.18); color: #4ade80; }}
  .denied {{ background: rgba(239,68,68,0.18); color: #f87171; }}
  .conditional {{ background: rgba(245,158,11,0.18); color: #fbbf24; }}
  .mono {{ font-family: ui-monospace, SFMono-Regular, Menlo, monospace; }}
</style>
</head>
<body>
<h1>{} — Declarative Access Permission Matrix</h1>
<p class="sub">Generated by <code>appstruct access matrix</code> · Scope: <code>declarations_only</code> (runtime Rust Policy is not evaluated).</p>
<div class="controls">
  <input id="filter" type="search" placeholder="Filter by entity, operation, or field..." oninput="filterRows()">
</div>
<div class="wrap">
<table id="matrix">
<thead><tr><th>Entity</th><th>Operation</th><th>Field</th>"#,
        escape_html(app_name),
        escape_html(app_name),
    );
    for actor in actors {
        let _ = write!(out, "<th>{}</th>", escape_html(&actor.label));
    }
    out.push_str("</tr></thead>\n<tbody>\n");
    for (index, row) in rows.iter().enumerate() {
        let field_label = row.field.as_deref().unwrap_or("—");
        let _ = write!(
            out,
            "<tr><td class=\"mono\">{}</td><td class=\"mono\">{}</td><td class=\"mono\">{}</td>",
            escape_html(&row.entity),
            escape_html(&row.operation),
            escape_html(field_label),
        );
        for actor in actors {
            let decision = actor.decisions[index];
            let _ = write!(
                out,
                "<td><span class=\"badge {}\" data-code=\"{}\">{}</span></td>",
                decision.css_class,
                decision.code,
                escape_html(decision.label),
            );
        }
        out.push_str("</tr>\n");
    }
    out.push_str(
        r"</tbody>
</table>
</div>
<script>
function filterRows() {
  const q = document.getElementById('filter').value.toLowerCase();
  for (const row of document.querySelectorAll('#matrix tbody tr')) {
    row.style.display = row.textContent.toLowerCase().includes(q) ? '' : 'none';
  }
}
</script>
</body>
</html>
",
    );
    out
}

fn escape_html(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}
