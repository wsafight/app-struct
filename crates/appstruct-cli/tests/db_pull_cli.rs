#[test]
fn database_pull_requires_database_url_without_creating_a_draft() {
    let project = copied_fixture("m2-project");
    let output = Command::new(env!("CARGO_BIN_EXE_appstruct"))
        .arg("--project")
        .arg(project.path())
        .args(["db", "pull"])
        .env_remove("DATABASE_URL")
        .output()
        .unwrap();

    assert_eq!(output.status.code(), Some(3));
    assert!(String::from_utf8_lossy(&output.stderr).contains("AS6304"));
    assert!(!project.path().join("spec/imported.yaml").exists());
}

