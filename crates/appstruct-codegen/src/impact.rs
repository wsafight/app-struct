use crate::{Artifact, ArtifactKind};
use appstruct_ir::{AppIr, EntityId, EntityIr, OnDeleteIr};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

pub(crate) fn plan(ir: &AppIr) -> Artifact {
    Artifact::text("ir/impact.md", render(ir), ArtifactKind::CanonicalIr)
}

struct ImpactGraph<'a> {
    entity_names: BTreeMap<&'a EntityId, &'a str>,
    inbound: BTreeMap<&'a EntityId, Vec<String>>,
    outbound: BTreeMap<&'a EntityId, Vec<String>>,
    aggregate_owners: BTreeMap<&'a EntityId, Vec<String>>,
    dashboard_refs: BTreeMap<&'a EntityId, BTreeSet<&'a str>>,
}

impl<'a> ImpactGraph<'a> {
    fn from_ir(ir: &'a AppIr) -> Self {
        let entity_names: BTreeMap<&EntityId, &str> = ir
            .entities
            .iter()
            .map(|entity| (&entity.id, entity.rust_name.as_str()))
            .collect();

        let mut inbound: BTreeMap<&EntityId, Vec<String>> = BTreeMap::new();
        let mut outbound: BTreeMap<&EntityId, Vec<String>> = BTreeMap::new();
        for relation in &ir.relations {
            let source_name = entity_names
                .get(&relation.source)
                .copied()
                .unwrap_or(relation.source.0.as_str());
            let target_name = entity_names
                .get(&relation.target)
                .copied()
                .unwrap_or(relation.target.0.as_str());
            let delete = on_delete_label(relation.on_delete);
            outbound
                .entry(&relation.source)
                .or_default()
                .push(format!("`{target_name}` (`on_delete: {delete}`)"));
            inbound
                .entry(&relation.target)
                .or_default()
                .push(format!("`{source_name}` (`on_delete: {delete}`)"));
        }

        let mut aggregate_owners: BTreeMap<&EntityId, Vec<String>> = BTreeMap::new();
        for entity in &ir.entities {
            for aggregate in &entity.views.aggregates {
                aggregate_owners
                    .entry(&aggregate.child)
                    .or_default()
                    .push(format!("`{}` (`{}`)", entity.rust_name, aggregate.name));
            }
        }

        let mut dashboard_refs: BTreeMap<&EntityId, BTreeSet<&str>> = BTreeMap::new();
        if let Some(dashboard) = &ir.dashboard {
            for widget in &dashboard.widgets {
                dashboard_refs
                    .entry(&widget.entity)
                    .or_default()
                    .insert(widget.id.as_str());
            }
        }

        Self {
            entity_names,
            inbound,
            outbound,
            aggregate_owners,
            dashboard_refs,
        }
    }
}

fn render(ir: &AppIr) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "<!-- @generated by AppStruct. Do not edit manually. -->\n"
    );
    let _ = writeln!(out, "# Change Impact Index: `{}`\n", ir.app.name);
    let _ = writeln!(
        out,
        "Deterministic dependency and blast-radius map derived from `ir/app-ir.json`."
    );
    let _ = writeln!(
        out,
        "Use this index before modifying an entity, relation, workflow, or module contract.\n"
    );

    let graph = ImpactGraph::from_ir(ir);
    write_enabled_modules(&mut out, ir);
    write_entity_summary(&mut out, ir, &graph);
    write_entity_details(&mut out, ir, &graph);
    write_custom_extensions(&mut out, ir);
    write_reports(&mut out, ir);
    out
}

fn write_enabled_modules(out: &mut String, ir: &AppIr) {
    let flags = [
        (ir.auth.enabled, "auth"),
        (ir.tenant.enabled, "tenant"),
        (ir.audit.enabled, "audit"),
        (ir.activity.enabled, "activity"),
        (ir.jobs.enabled, "jobs"),
        (ir.file.enabled, "file"),
        (ir.mail.enabled, "mail"),
        (ir.report.enabled, "report"),
        (ir.billing.enabled, "billing"),
        (ir.webhooks.enabled, "webhooks"),
        (ir.realtime.enabled, "realtime"),
    ];
    let modules: Vec<&str> = flags
        .into_iter()
        .filter_map(|(enabled, name)| enabled.then_some(name))
        .collect();

    let _ = writeln!(out, "## Enabled Platform Modules\n");
    if modules.is_empty() {
        let _ = writeln!(out, "- None\n");
    } else {
        let _ = writeln!(out, "- {}\n", modules.join(", "));
    }
}

fn write_entity_summary(out: &mut String, ir: &AppIr, graph: &ImpactGraph<'_>) {
    let _ = writeln!(out, "## Entity Summary\n");
    let _ = writeln!(
        out,
        "| Entity | Table | Tenant Scoped | Audit | Soft Delete | Workflow | Aggregates | Outbound | Inbound |"
    );
    let _ = writeln!(
        out,
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"
    );
    for entity in &ir.entities {
        let workflow = entity.workflow.as_ref().map_or_else(
            || "-".to_owned(),
            |wf| format!("{} transitions", wf.transitions.len()),
        );
        let out_count = graph.outbound.get(&entity.id).map_or(0, Vec::len);
        let in_count = graph.inbound.get(&entity.id).map_or(0, Vec::len);
        let _ = writeln!(
            out,
            "| `{}` | `{}` | {} | {} | {} | {} | {} | {} | {} |",
            entity.rust_name,
            entity.table_name,
            yes_no(entity.tenant_scoped),
            yes_no(entity.audit_enabled),
            yes_no(entity.views.soft_delete),
            workflow,
            entity.views.aggregates.len(),
            out_count,
            in_count,
        );
    }
    let _ = writeln!(out);
}

fn write_entity_details(out: &mut String, ir: &AppIr, graph: &ImpactGraph<'_>) {
    let _ = writeln!(out, "## Entity Change Impact\n");
    for entity in &ir.entities {
        write_entity_detail(out, entity, graph);
    }
}

fn write_entity_detail(out: &mut String, entity: &EntityIr, graph: &ImpactGraph<'_>) {
    let _ = writeln!(
        out,
        "### `{}` (`{}`)\n",
        entity.rust_name, entity.table_name
    );
    let out_list = graph.outbound.get(&entity.id).cloned().unwrap_or_default();
    let in_list = graph.inbound.get(&entity.id).cloned().unwrap_or_default();
    let _ = writeln!(out, "- **Outbound relations**: {}", join_or_none(&out_list));
    let _ = writeln!(out, "- **Inbound dependents**: {}", join_or_none(&in_list));
    if !entity.views.aggregates.is_empty() {
        let children = entity
            .views
            .aggregates
            .iter()
            .map(|agg| {
                let child = graph
                    .entity_names
                    .get(&agg.child)
                    .copied()
                    .unwrap_or(agg.child.0.as_str());
                format!("`{}` -> `{child}` (max {})", agg.name, agg.max_items)
            })
            .collect::<Vec<_>>();
        let _ = writeln!(out, "- **Owns aggregates**: {}", children.join(", "));
    }
    if let Some(owners) = graph.aggregate_owners.get(&entity.id) {
        let _ = writeln!(out, "- **Aggregate child of**: {}", owners.join(", "));
    }
    if let Some(workflow) = &entity.workflow {
        let transitions = workflow
            .transitions
            .iter()
            .map(|tr| format!("`{}` -> `{}`", tr.name, tr.to))
            .collect::<Vec<_>>();
        let _ = writeln!(
            out,
            "- **Workflow transitions**: {}",
            join_or_none(&transitions)
        );
    }
    let ui_components = entity
        .fields
        .iter()
        .filter_map(|field| field.ui_component.as_deref())
        .collect::<BTreeSet<_>>();
    if !ui_components.is_empty() {
        let formatted = ui_components
            .into_iter()
            .map(|component| format!("`{component}`"))
            .collect::<Vec<_>>();
        let _ = writeln!(out, "- **Custom UI components**: {}", formatted.join(", "));
    }
    if let Some(widgets) = graph.dashboard_refs.get(&entity.id) {
        let formatted = widgets
            .iter()
            .map(|widget| format!("`{widget}`"))
            .collect::<Vec<_>>();
        let _ = writeln!(out, "- **Dashboard widgets**: {}", formatted.join(", "));
    }
    let _ = writeln!(out);
}

fn write_custom_extensions(out: &mut String, ir: &AppIr) {
    if ir.commands.is_empty() && ir.queries.is_empty() && ir.pages.is_empty() {
        return;
    }
    let _ = writeln!(out, "## Custom Extensions\n");
    if !ir.commands.is_empty() {
        let names = ir
            .commands
            .iter()
            .map(|item| format!("`{}`", item.rust_name))
            .collect::<Vec<_>>();
        let _ = writeln!(out, "- **Commands**: {}", names.join(", "));
    }
    if !ir.queries.is_empty() {
        let names = ir
            .queries
            .iter()
            .map(|item| format!("`{}`", item.rust_name))
            .collect::<Vec<_>>();
        let _ = writeln!(out, "- **Queries**: {}", names.join(", "));
    }
    if !ir.pages.is_empty() {
        let names = ir
            .pages
            .iter()
            .map(|item| format!("`{}` (`{}`)", item.rust_name, item.path))
            .collect::<Vec<_>>();
        let _ = writeln!(out, "- **Custom pages**: {}", names.join(", "));
    }
    let _ = writeln!(out);
}

fn write_reports(out: &mut String, ir: &AppIr) {
    if !ir.report.enabled || ir.report.templates.is_empty() {
        return;
    }
    let _ = writeln!(out, "## Report Templates\n");
    for template in &ir.report.templates {
        let _ = writeln!(
            out,
            "- `{}` v{} (data schema v{})",
            template.name, template.version, template.data_schema_version
        );
    }
    let _ = writeln!(out);
}

fn on_delete_label(on_delete: OnDeleteIr) -> &'static str {
    match on_delete {
        OnDeleteIr::Restrict => "restrict",
        OnDeleteIr::Cascade => "cascade",
        OnDeleteIr::SetNull => "set_null",
    }
}

fn yes_no(value: bool) -> &'static str {
    if value { "yes" } else { "no" }
}

fn join_or_none(items: &[String]) -> String {
    if items.is_empty() {
        "none".to_owned()
    } else {
        items.join(", ")
    }
}
